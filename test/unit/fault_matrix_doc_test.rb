require 'test/unit'
require 'vxlan/fault'

# docs/fault-matrix.md is generated by test/lab/fault_matrix_test.rb,
# which needs root. This needs none: it fails when the catalog gains or
# loses an entry the document does not show, so a new fault cannot go in
# without the matrix being run again. As bgp4r's doc tests.
class Fault_matrix_doc_Test < Test::Unit::TestCase
  DOC = File.expand_path('../../docs/fault-matrix.md', __dir__)

  def rows
    File.read(DOC).lines.grep(/\A\| `/).to_h { |l| [l[/\A\| `([^`]+)`/, 1], l.split('|').map(&:strip)] }
  end

  def test_every_catalog_entry_and_the_baseline_has_a_row
    assert_equal ['valid'] + VXLAN::Fault.names.map(&:to_s), rows.keys
  end

  def test_each_row_says_what_the_rfc_expects_as_the_catalog_does
    VXLAN::Fault.catalog.each do |e|
      assert_match(/\A#{e[:expect]} \(/, rows[e[:name].to_s][3], e[:name].to_s)
    end
  end

  def test_it_says_it_is_generated
    assert_match(/\*\*Generated\*\* by `test\/lab\/fault_matrix_test.rb` on \d{4}-\d\d-\d\d, Linux \S+,/, File.read(DOC))
  end
end
